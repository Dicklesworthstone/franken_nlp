//! Data-contract discovery only; schema publication never reads a suite or key.
use serde_json::{Value, json};
use super::{PROTOCOL, SCHEMA_VERSION};

pub(super) fn document(operation: &str) -> Value {
    let digest = json!({"type":"string","pattern":"^[0-9a-f]{64}$"});
    let text = json!({"type":"string","minLength":1});
    let identity_names = ["schema_version", "source_revision", "logical_model_digest", "artifact_format",
        "quant_recipe", "packing_set_digest", "tokenizer_digest", "template_digest", "task_spec", "taskir_digest",
        "prompt_digest", "grammar_compiler_version", "schema_digest", "numerics_profile", "kv_dtype",
        "sampler_version", "thinking_mode", "tool_mode", "calibration_digest", "decision_policy_digest",
        "backend_semantic_version", "host_class", "compiler_identity"];
    let mut identity = serde_json::Map::new();
    for field in identity_names {
        let schema = match field {
            "schema_version" => json!({"const":1}),
            "thinking_mode" => json!({"enum":["disabled","enabled"]}),
            "tool_mode" => json!({"enum":["none","xml","json"]}),
            "host_class" | "compiler_identity" => json!({"type":["string","null"]}),
            "numerics_profile" => json!({"type":"string","pattern":"^(hf-bf16-eager|diagnostic-f32|strict-quantized-v(0|[1-9][0-9]*)|fast-v(0|[1-9][0-9]*))$"}),
            field if field.ends_with("_digest") => digest.clone(),
            _ => text.clone(),
        };
        identity.insert(field.to_owned(), schema);
    }
    let ids = json!({"type":"array","minItems":1,"uniqueItems":true,"items":{"type":"string","minLength":1}});
    json!({
        "schema_version": SCHEMA_VERSION,
        "protocol": PROTOCOL,
        "operation": operation,
        "backend": "scored",
        "evidence": "provided_observations",
        "native_model_replay": false,
        "activation_authority": false,
        "framing": "one complete canonical UTF-8 JSON report followed by one LF; observation input is NDJSON",
        "key": {"file_bytes":32,"argv_secret":false,"namespace_and_key_id":"nonsecret bounded receipt identifiers",
            "file_profile":"Linux x86_64/aarch64, private parent directory, protected regular key; no symlinks"},
        "invariants": [
            "Reject duplicate JSON keys and unknown fields at every authority boundary.",
            "The suite pins exact observation-file bytes before metrics are produced.",
            "Every declared ID occurs once in its declared split; undeclared IDs and duplicate units are rejected.",
            "Development, calibration and locked_test IDs and input units are disjoint.",
            "Fitting consumes only calibration rows; reported reliability consumes only locked_test rows.",
            "Probabilities denote the declared positive binary event; arbitrary logits and multiclass scores are invalid substitutes.",
            "Insufficient samples are successful typed refusals without fitted artifacts or confident metrics.",
            "Private IDs, unit hashes, input-byte hashes and execution keys are exported through keyed commitments.",
            "Qualification pairs identical suite scope, split IDs, input units and human labels; only declared model/implementation fields may differ.",
            "Qualification gates use supplied locked-test point estimates; marginal bootstrap intervals do not certify gate confidence.",
            "Model execution, project quality, population exchangeability and activation permission are not inferred.",
            "A report file is create-new and fully staged; a failed computation emits no successful output prefix."
        ],
        "apply_calibration": {"file":"complete fnlp.assay.scored calibrate report",
            "independent_pin":"--expected-calibration-sha256 hashes the complete file including newline",
            "required_context":["--as-of YYYY-MM-DD","--shift-assessment in-distribution|detected"],
            "detected_shift":"--shift-indicator is required only with detected"},
        "qualification": {"candidate":"--suite and --observations",
            "baseline":"--baseline-suite and --baseline-observations; regular files, never a second stdin",
            "policy":"--gates is strict JSON; all fields required",
            "host_scope":"--host-scope is a caller-declared nonsecret identifier, not observed hardware evidence",
            "gate_basis":"point_estimates","receipt_grade":"audit_only",
            "successful_outcomes":["passed","rejected","insufficient_data"],
            "bootstrap_budget":"the combined candidate and baseline draws must fit --max-bootstrap-draws"},
        "limits": {"manifest_bytes_default":1048576,"observation_bytes_default":67108864,
            "line_bytes_default":65536,"rows_default":100000,"complete_output_bytes_default":4194304,
            "bootstrap_resamples_default":200,"bootstrap_resample_ceiling_default":1000,
            "bootstrap_draw_ceiling_default":10000000,"minimum_samples_default":20,
            "confidence_level_default":0.95,"acceptance_threshold_default":0.8,"bootstrap_seed_default":0},
        "json_schema": {
            "$schema":"https://json-schema.org/draft/2020-12/schema",
            "$defs": {
                "commitment":{"type":"object","additionalProperties":false,
                    "required":["domain","key_id","hmac_sha256"],
                    "properties":{"domain":{"enum":["execution_identity","input","output","configuration"]},
                        "key_id":text,"hmac_sha256":digest}},
                "dataset_metadata":{"type":"object","additionalProperties":false,
                    "required":["dataset_id","dataset_version","named_population","positive_label","negative_label",
                        "task_spec","model_recipe_id","prompt_template_sha256","numerics_profile","thinking_mode"],
                    "properties":{"dataset_id":text,"dataset_version":text,"named_population":text,
                        "positive_label":text,"negative_label":text,"task_spec":text,"model_recipe_id":text,
                        "prompt_template_sha256":digest,"numerics_profile":text,
                        "thinking_mode":{"enum":["disabled","enabled"]}}},
                "dataset_bindings":{"type":"object","additionalProperties":false,
                    "required":["metadata","suite","input","execution_identity","splits"],
                    "properties":{"metadata":{"$ref":"#/$defs/dataset_metadata"},
                        "suite":{"$ref":"#/$defs/commitment"},"input":{"$ref":"#/$defs/commitment"},
                        "execution_identity":{"$ref":"#/$defs/commitment"},
                        "splits":{"type":"object","additionalProperties":false,
                            "required":["development","calibration","locked_test"],
                            "properties":{"development":{"$ref":"#/$defs/commitment"},
                                "calibration":{"$ref":"#/$defs/commitment"},"locked_test":{"$ref":"#/$defs/commitment"}}}}},
                "execution_identity":{"type":"object","additionalProperties":false,"required":identity_names,"properties":identity},
                "splits":{"type":"object","additionalProperties":false,
                    "required":["development","calibration","locked_test"],
                    "properties":{"development":ids,"calibration":ids,"locked_test":ids}},
                "suite":{"type":"object","additionalProperties":false,
                    "required":["schema_version","task","dataset_id","dataset_version","named_population",
                        "positive_label","negative_label","execution_identity","expected_input_sha256","splits"],
                    "properties":{"schema_version":{"const":1},"task":{"const":"binary_event"},
                        "dataset_id":text,"dataset_version":text,"named_population":text,
                        "positive_label":text,"negative_label":text,
                        "execution_identity":{"$ref":"#/$defs/execution_identity"},
                        "expected_input_sha256":digest,"splits":{"$ref":"#/$defs/splits"}}},
                "observation":{"type":"object","additionalProperties":false,
                    "required":["schema_version","id","split","probability","positive","unit_sha256"],
                    "properties":{"schema_version":{"const":1},"id":text,
                        "split":{"enum":["development","calibration","locked_test"]},
                        "probability":{"type":"number","minimum":0,"maximum":1},"positive":{"type":"boolean"},
                        "unit_sha256":digest}},
                "bootstrap_options":{"type":"object","additionalProperties":false,
                    "required":["resamples","confidence_level","seed"],
                    "properties":{"resamples":{"type":"integer","minimum":2,"maximum":10000},
                        "confidence_level":{"type":"number","exclusiveMinimum":0,"exclusiveMaximum":1},
                        "seed":{"type":"integer","minimum":0,"maximum":18446744073709551615_u64}}},
                "eval_options":{"type":"object","additionalProperties":false,
                    "required":["minimum_samples","acceptance_threshold","bootstrap"],
                    "properties":{"minimum_samples":{"type":"integer","minimum":5,"maximum":100000},
                        "acceptance_threshold":{"type":"number","minimum":0,"maximum":1},
                        "bootstrap":{"$ref":"#/$defs/bootstrap_options"}}},
                "confidence_interval":{"type":"object","additionalProperties":false,
                    "required":["lower","upper","confidence_level","resamples"],
                    "properties":{"lower":{"type":"number","minimum":0,"maximum":1},
                        "upper":{"type":"number","minimum":0,"maximum":1},
                        "confidence_level":{"type":"number","exclusiveMinimum":0,"exclusiveMaximum":1},
                        "resamples":{"type":"integer","minimum":2,"maximum":10000}}},
                "locked_test_metrics":{"type":"object","additionalProperties":false,
                    "required":["rows","ece","brier","acceptance_threshold","accepted","abstained",
                        "selective_risk","ece_interval","brier_interval","selective_risk_interval"],
                    "properties":{"rows":{"type":"integer","minimum":5},
                        "ece":{"type":"number","minimum":0,"maximum":1},
                        "brier":{"type":"number","minimum":0,"maximum":1},
                        "acceptance_threshold":{"type":"number","minimum":0,"maximum":1},
                        "accepted":{"type":"integer","minimum":0},"abstained":{"type":"integer","minimum":0},
                        "selective_risk":{"type":["number","null"],"minimum":0,"maximum":1},
                        "ece_interval":{"$ref":"#/$defs/confidence_interval"},
                        "brier_interval":{"$ref":"#/$defs/confidence_interval"},
                        "selective_risk_interval":{"anyOf":[{"$ref":"#/$defs/confidence_interval"},{"type":"null"}]}}},
                "measurement":{"oneOf":[
                    {"type":"object","additionalProperties":false,"required":["status","metrics"],
                        "properties":{"status":{"const":"measured"},"metrics":{"$ref":"#/$defs/locked_test_metrics"}}},
                    {"type":"object","additionalProperties":false,"required":["status","split","rows","minimum_samples"],
                        "properties":{"status":{"const":"insufficient_data"},"split":{"const":"locked_test"},
                            "rows":{"type":"integer","minimum":0},"minimum_samples":{"type":"integer","minimum":5,"maximum":100000}}}
                ]},
                "evaluation":{"type":"object","additionalProperties":false,
                    "required":["schema_version","task","evidence","activation_authority","bindings","options","measurement"],
                    "properties":{"schema_version":{"const":1},"task":{"const":"binary_event"},
                        "evidence":{"const":"provided_observations"},"activation_authority":{"const":false},
                        "bindings":{"$ref":"#/$defs/dataset_bindings"},"options":{"$ref":"#/$defs/eval_options"},
                        "measurement":{"$ref":"#/$defs/measurement"}}},
                "qualification_gates":{"type":"object","additionalProperties":false,
                    "required":["schema_version","max_brier_increase","max_ece_increase","max_selective_risk",
                        "min_acceptance_rate","minimum_accepted"],
                    "properties":{"schema_version":{"const":1},
                        "max_brier_increase":{"type":"number","minimum":-1,"maximum":1},
                        "max_ece_increase":{"type":"number","minimum":-1,"maximum":1},
                        "max_selective_risk":{"type":"number","minimum":0,"maximum":1},
                        "min_acceptance_rate":{"type":"number","minimum":0,"maximum":1},
                        "minimum_accepted":{"type":"integer","minimum":1,
                            "description":"Must not exceed the admitted max_rows limit."}}},
                "gate_result":{"type":"object","additionalProperties":false,
                    "required":["name","observed","limit","passed"],
                    "properties":{"name":{"enum":["brier_increase","ece_increase","selective_risk","acceptance_rate","accepted_rows"]},
                        "observed":{"type":["number","null"]},"limit":{"type":"number"},"passed":{"type":"boolean"}}},
                "paired_summary":{"type":"object","additionalProperties":false,
                    "required":["rows","mean_brier_change","candidate_better","candidate_worse","equal"],
                    "properties":{"rows":{"type":"integer","minimum":5},
                        "mean_brier_change":{"type":"number","minimum":-1,"maximum":1},
                        "candidate_better":{"type":"integer","minimum":0},
                        "candidate_worse":{"type":"integer","minimum":0},"equal":{"type":"integer","minimum":0}}},
                "qualification_decision":{"oneOf":[
                    {"type":"object","additionalProperties":false,"required":["status","comparisons","paired"],
                        "properties":{"status":{"enum":["passed","rejected"]},
                            "comparisons":{"type":"array","minItems":5,"maxItems":5,"items":{"$ref":"#/$defs/gate_result"}},
                            "paired":{"$ref":"#/$defs/paired_summary"}}},
                    {"type":"object","additionalProperties":false,"required":["status","rows","minimum_samples"],
                        "properties":{"status":{"const":"insufficient_data"},"rows":{"type":"integer","minimum":0},
                            "minimum_samples":{"type":"integer","minimum":5,"maximum":100000}}}
                ]},
                "qualification_report":{"type":"object","additionalProperties":false,
                    "required":["schema_version","task","evidence","activation_authority","receipt_grade",
                        "declared_host_scope","host_scope_evidence","gate_basis","gates","policy_commitment",
                        "candidate","baseline","decision","seal"],
                    "properties":{"schema_version":{"const":1},"task":{"const":"binary_event"},
                        "evidence":{"const":"provided_observations"},"activation_authority":{"const":false},
                        "receipt_grade":{"const":"audit_only"},"declared_host_scope":{"type":"string","minLength":1,"maxLength":256},
                        "host_scope_evidence":{"const":"caller_declared"},"gate_basis":{"const":"point_estimates"},
                        "gates":{"$ref":"#/$defs/qualification_gates"},"policy_commitment":{"$ref":"#/$defs/commitment"},
                        "candidate":{"$ref":"#/$defs/evaluation"},"baseline":{"$ref":"#/$defs/evaluation"},
                        "decision":{"$ref":"#/$defs/qualification_decision"},"seal":{"$ref":"#/$defs/commitment"}}},
                "report_envelope":{"type":"object","additionalProperties":false,
                    "required":["schema_version","protocol","operation","evidence","activation_authority","report"],
                    "properties":{"schema_version":{"const":1},"protocol":{"const":PROTOCOL},
                        "operation":{"enum":["eval","calibrate","qualify"]},"evidence":{"const":"provided_observations"},
                        "activation_authority":{"const":false},"report":{"type":"object"}},
                    "allOf":[{"if":{"properties":{"operation":{"const":"qualify"}}},
                        "then":{"properties":{"report":{"$ref":"#/$defs/qualification_report"}}}}]},
                "error":{"type":"object","additionalProperties":false,
                    "required":["schema_version","protocol","event","code","reason"],
                    "properties":{"schema_version":{"const":1},"protocol":{"const":PROTOCOL},
                        "event":{"const":"assay_error"},"code":{"type":"integer","minimum":1,"maximum":10},
                        "reason":{"type":"string","pattern":"^[a-z0-9_]+$"}}}
            }
        }
    })
}
